import esbuild from "esbuild";
import process from "process";
// Node's own list, via `node:module`. The `builtin-modules` package did the same thing and is
// flagged by the store's `depend/ban-dependencies` check as a needless dependency.
import { builtinModules as builtins } from "node:module";
import { readFile } from "node:fs/promises";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, visit the plugin's github repository
*/
`;

const prod = process.argv[2] === "production";

// Bundling `ssh2` costs every user ~730 kB of `main.js` -- 1.5 MB to 2.3 MB -- including free users,
// whom the licence gate will never let near it. Accepted, and worth writing down rather than
// discovering later: an Obsidian plugin is one file, so there is no split to defer it into, and a
// `import()` at the point of use moves nothing out of the download. The alternative is shipping the
// direct-device transport as a separate plugin, which is a much larger decision than a megabyte.
//
// `ssh2` asks for a compiled cipher accelerator inside a `try {} catch {}`. A `.node` file cannot be
// bundled and must not be shipped, so every request for one is replaced by a module that throws --
// which is precisely what an absent optional dependency does, and lands in the catch ssh2 has for
// it. An *empty* module would be worse than nothing: ssh2 reads `!!binding` to decide the
// accelerator is there, so a stub object would be used and would fail on the first cipher.
// See src/shims/cpu-features.cjs for the other half of the same story.
const optionalNativeAddons = {
	name: "optional-native-addons",
	setup(build) {
		build.onResolve({ filter: /\.node$/ }, (args) => ({ path: args.path, namespace: "optional-native" }));
		build.onLoad({ filter: /.*/, namespace: "optional-native" }, () => ({
			contents: 'throw new Error("Tagged Sync: native addons are not bundled.");',
			loader: "js",
		}));

		// ssh2 detects BigInt *literal* support the only way that works on a runtime that cannot parse
		// them -- by compiling one at runtime. Obsidian's automated review reads the built `main.js` and
		// rejects `new Function` outright, however unreachable the code is (the same rule that forced the
		// jszip polyfill aliases above). Electron has parsed BigInt literals for its entire supported
		// range, so the probe and its answer are the same value here, and the literal is written in.
		build.onLoad({ filter: /ssh2[/\\]lib[/\\]protocol[/\\]node-fs-compat\.js$/ }, async (args) => {
			const source = await readFile(args.path, "utf8");
			const patched = source.replace("new Function('return 2n ** 32n')()", "2n ** 32n");
			if (patched === source) throw new Error("ssh2's BigInt probe moved: re-check the bundle scan rule");
			return { contents: patched, loader: "js" };
		});
	},
};

// One entry point and one output. `src/entry.ts` registers every backend, including the paid ones
// in `pro/`, which are unlocked at runtime by the licence rather than by which file was built. What
// you see here is what users get.
const entryPoint = "src/entry.ts";
console.log(`entry: ${entryPoint}`);

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: [entryPoint],
	bundle: true,
	// Keeps Obsidian's automated review happy. `rmapi-js` depends on jszip, whose `browser` field
	// resolves the package to the pre-built `dist/jszip.min.js`; that bundle has `setimmediate` and
	// `immediate` (via `lie`) baked in, and their environment probes create `<script>` elements and
	// call `new Function` -- 4 + 1 sites that the store's scanner reads out of `main.js` and rejects.
	// Pointing jszip at its own source lets those two polyfills resolve as ordinary packages, so
	// they can be swapped for the shims in `src/shims/`. See .scratch/public-repo-and-pipeline.
	alias: {
		jszip: "jszip/lib/index.js",
		setimmediate: "./src/shims/setimmediate.ts",
		lie: "./src/shims/lie.cjs",
		"cpu-features": "./src/shims/cpu-features.cjs",
	},
	plugins: [optionalNativeAddons],
	// Rewrites free-identifier `fetch` references inside the bundle (rmapi-js has no fetch
	// injection point) to the CORS-free requestUrl shim. Bundle-scoped: the global fetch of the
	// Obsidian process is never touched. Rationale in src/obsidian-fetch.ts.
	inject: ["src/fetch-shim.ts"],
	external: [
		"obsidian",
		"electron",
		// KaitaiStream (kaitai-struct) lazily requires this for encodings we never use; not an
		// installed dependency, so it must stay external rather than be bundled. Same fix as the
		// inspect:rm dev script's --external:iconv-lite.
		"iconv-lite",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	outfile: "main.js",
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
